export function getAdministrativeUnitById(id: string): VietnamAdministrativeUnit | undefined {
  return VIETNAM_ADMINISTRATIVE_UNITS.find((u) => u.id === id);
}

export function findAdministrativeUnitForDestination(destId: string): VietnamAdministrativeUnit | undefined {
  return VIETNAM_ADMINISTRATIVE_UNITS.find((u) => u.touristDestinationIds.includes(destId));
}

export function searchAdministrativeUnits(query: string): VietnamAdministrativeUnit[] {
  const q = query.toLowerCase().trim();
  if (!q) return VIETNAM_ADMINISTRATIVE_UNITS;

  return VIETNAM_ADMINISTRATIVE_UNITS.filter((u) => {
    return (
      u.officialVietnameseName.toLowerCase().includes(q) ||
      u.englishName.toLowerCase().includes(q) ||
      u.administrativeSeat.toLowerCase().includes(q) ||
      u.mergedPre2025Provinces.some((p) => p.toLowerCase().includes(q)) ||
      u.historicalAliases.some((a) => a.toLowerCase().includes(q))
    );
  });
}
